      );
      print('3️⃣ ${step3.statusProgressPesanan}: ${step3.deskripsi}\n');

      // Step 4: Selesai, minta review
      final step4 = createReview(
        noOrder: 'ORD-001',
        senderId: 'VENDOR-456',
      );
      print('4️⃣ ${step4.statusProgressPesanan}: ${step4.deskripsi}\n');

      // Step 5: Customer puas, pesanan selesai
      final step5 = createSelesai(
        noOrder: 'ORD-001',
