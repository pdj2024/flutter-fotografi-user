      );
      print('1️⃣ ${step1.statusProgressPesanan}: ${step1.deskripsi}\n');

      // Step 2: Customer bayar, vendor terima
      final step2 = createPersiapan(
        noOrder: 'ORD-001',
        senderId: 'VENDOR-456',
      );
      print('2️⃣ ${step2.statusProgressPesanan}: ${step2.deskripsi}\n');

      // Step 3: Vendor mulai kerjakan
      final step3 = createProses(
        noOrder: 'ORD-001',
